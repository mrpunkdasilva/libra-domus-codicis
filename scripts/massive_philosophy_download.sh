echo "MASSIVE DOWNLOAD COMPLETE"
echo "=========================================="
echo "Downloaded: $downloaded"
echo "Skipped (existing): $skipped"
echo "Failed: $failed"
echo "Total: $total"
echo ""
echo "Files in $DOWNLOAD_DIR:"
