# Combine all arrays
ALL_BOOKS=("${NIETZSCHE_URLS[@]}" "${PLATO_URLS[@]}" "${ARISTOTLE_URLS[@]}" "${STOICISM_URLS[@]}" "${EXISTENTIALISM_URLS[@]}" "${MODERN_PHILOSOPHY_URLS[@]}" "${GERMAN_PHILOSOPHY_URLS[@]}" "${FRENCH_PHILOSOPHY_URLS[@]}")

# Download all books
total=${#ALL_BOOKS[@]}
current=0
downloaded=0
skipped=0
failed=0

echo "Total books to download: $total"
echo ""

for entry in "${ALL_BOOKS[@]}"; do
    current=$((current + 1))
    url=$(echo "$entry" | cut -d'|' -f1)
    title=$(echo "$entry" | cut -d'|' -f2)

    # Create filename from title
    filename=$(echo "$title" | sed 's/[^a-zA-Z0-9._-]/_/g' | sed 's/__*/_/g' | head -c 100)
    filename="${filename}.epub"

    # Check if already exists
    if [ -f "$DOWNLOAD_DIR/$filename" ]; then
        skipped=$((skipped + 1))
        if [ $((current % 50)) -eq 0 ]; then
            echo "[$current/$total] Progress: $downloaded downloaded, $skipped skipped"
        fi
        continue
    fi

    # Download
    if wget -q --timeout=20 --tries=1 -O "$DOWNLOAD_DIR/$filename" "$url" 2>/dev/null; then
        size=$(stat -c%s "$DOWNLOAD_DIR/$filename" 2>/dev/null || stat -f%z "$DOWNLOAD_DIR/$filename" 2>/dev/null || echo "0")
        if [ "$size" -gt 5000 ]; then
            downloaded=$((downloaded + 1))
            if [ $((downloaded % 10)) -eq 0 ]; then
                echo "[$current/$total] Downloaded $downloaded books so far..."
            fi
        else
            rm -f "$DOWNLOAD_DIR/$filename"
            failed=$((failed + 1))
        fi
    else
        rm -f "$DOWNLOAD_DIR/$filename"
        failed=$((failed + 1))
    fi

    # Rate limiting
    sleep 0.5
done

echo ""
